-- Initial schema, generated from the JPA entities by Hibernate and cleaned up by hand.
-- Enum columns (role, unit, slot) are plain varchars without CHECK constraints,
-- so adding an enum constant doesn't need a migration.

create table app_user (
    id             bigint generated by default as identity primary key,
    username       varchar(255) not null unique,
    email          varchar(255) not null unique,
    password       varchar(255) not null,
    role           varchar(255) not null,
    email_verified boolean      not null
);

create table email_verification_token (
    id         bigint generated by default as identity primary key,
    user_id    bigint                   not null references app_user,
    token_hash varchar(255)             not null unique,
    expires_at timestamp(6) with time zone not null
);

create table recipe (
    id               bigint generated by default as identity primary key,
    owner_id         bigint references app_user,
    name             varchar(255),
    description      varchar(255),
    preparation_time integer not null,
    portions         integer not null,
    shared           boolean not null,
    -- Nutrition embeddable, per portion
    fat              numeric(7, 1),
    carbs            numeric(7, 1),
    protein          numeric(7, 1),
    calories         integer,
    suggested        boolean
);

create table recipe_ingredient (
    recipe_id bigint       not null references recipe,
    position  integer      not null,
    amount    numeric(10, 3),
    unit      varchar(255),
    name      varchar(255),
    primary key (position, recipe_id)
);

create table step (
    id          bigint generated by default as identity primary key,
    recipe_id   bigint  not null references recipe,
    step_order  integer not null,
    instruction varchar(255)
);

create table meal_plan_entry (
    id        bigint generated by default as identity primary key,
    user_id   bigint       not null references app_user,
    plan_date date         not null,
    slot      varchar(255) not null,
    recipe_id bigint       not null references recipe,
    unique (user_id, plan_date, slot)
);

create table user_settings (
    id           bigint generated by default as identity primary key,
    user_id      bigint  not null unique references app_user,
    use_ai       boolean not null,
    protein_goal numeric(38, 2),
    protein_min  numeric(38, 2),
    protein_max  numeric(38, 2),
    kcal_goal    numeric(38, 2),
    kcal_min     numeric(38, 2),
    kcal_max     numeric(38, 2)
);

-- nutrition cache (global, not per user)
create table ingredient_nutrition (
    id               bigint generated by default as identity primary key,
    name             varchar(255) not null unique,
    fat_per_gram     numeric(10, 6),
    carbs_per_gram   numeric(10, 6),
    protein_per_gram numeric(10, 6)
);

create table ingredient_unit_weight (
    id    bigint generated by default as identity primary key,
    name  varchar(255)   not null,
    unit  varchar(255)   not null,
    grams numeric(10, 3) not null,
    unique (name, unit)
);
